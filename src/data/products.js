export function getAllCategories() {
  return categories.map(({ products, ...cat }) => cat);
}

export function getCategoryBySlug(slug) {
  return categories.find(cat => cat.slug === slug);
}

export function getProductBySlug(categorySlug, productSlug) {
  const cat = getCategoryBySlug(categorySlug);
  if (!cat) return null;
  return cat.products.find(prod => prod.slug === productSlug) || null;
}

export function getAllProducts() {
  const list = [];
  categories.forEach(cat => {
    cat.products.forEach(prod => {
      list.push(prod);
    });
  });
  return list;
}

export function getRelatedProducts(productSlugs) {
  const list = getAllProducts();
  return list.filter(prod => productSlugs.includes(prod.slug));
}
